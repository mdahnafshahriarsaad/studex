export type Language = 'English' | 'Bengali';

// ─── Utility Functions ──────────────────────────────────────────────────────────

const BANGLA_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'] as const;

/** Convert a number to Bangla digits: 123 → ১২৩ */
export function toBanglaNumber(num: number | string): string {
  return String(num).replace(/[0-9]/g, (d) => BANGLA_DIGITS[parseInt(d)] || d);
}

/** Format a number with optional Bangla conversion */
export function formatNumber(num: number, lang?: Language): string {
  const l = lang || getCurrentLanguage();
  if (l === 'Bengali') return toBanglaNumber(num);
  return String(num);
}

/** Get month name (1-12) translated */
export function getMonthName(month: number, lang?: Language): string {
  const l = lang || getCurrentLanguage();
  const key = `month.${month}`;
  return translations[l]?.[key] || translations.English[key] || 'January';
}

/** Get short day name (sun-sat) translated */
export function getDayNameShort(dayIndex: number, lang?: Language): string {
  const l = lang || getCurrentLanguage();
  const days = ['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat'];
  const key = `day.${days[dayIndex]}`;
  return translations[l]?.[key] || translations.English[key] || 'Sun';
}

/** Get full day name (sunday-saturday) translated */
export function getDayNameFull(dayIndex: number, lang?: Language): string {
  const l = lang || getCurrentLanguage();
  const days = ['sunday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'];
  const key = `dayfull.${days[dayIndex]}`;
  return translations[l]?.[key] || translations.English[key] || 'Sunday';
}

/** Get all month names in an array */
export function getMonthNames(lang?: Language): string[] {
  return Array.from({ length: 12 }, (_, i) => getMonthName(i + 1, lang));
}

/** Get short day names in an array (Sun-Sat) */
export function getDayNamesShort(lang?: Language): string[] {
  return Array.from({ length: 7 }, (_, i) => getDayNameShort(i, lang));
}

/** Translate a subject name to Bengali if available */
export function translateSubjectName(name: string, lang?: Language): string {
  const l = lang || getCurrentLanguage();
  if (l === 'Bengali' && subjectNameMap[name]) {
    return subjectNameMap[name];
  }
  return name;
}

